import Link from "next/link";
import { DeadlineChip } from "@/components/badges";
import { PrintButton } from "@/components/print-button";
import { isOpen } from "@/lib/dashboard";
import { formatDate, formatMoney, formatRange } from "@/lib/dates";
import { profile } from "@/lib/profile";
import { getLastScan, listOpportunities } from "@/lib/store";
import type { Opportunity } from "@/lib/types";

export const dynamic = "force-dynamic";

/**
 * Printable report in the layout of the October 2026 sample report:
 * recommended (6+) with full analysis, possible (4-5) with a short rationale,
 * and not recommended (1-3) as a one-line list. Print to PDF from the browser.
 */
export default async function ReportPage() {
  const [all, lastScan] = await Promise.all([listOpportunities(), getLastScan()]);
  const evaluated = all.filter((o) => o.evaluation && isOpen(o)).sort((a, b) => b.evaluation!.score - a.evaluation!.score);
  const recommended = evaluated.filter((o) => o.evaluation!.score >= 6);
  const possible = evaluated.filter((o) => o.evaluation!.score >= 4 && o.evaluation!.score < 6);
  const notRecommended = evaluated.filter((o) => o.evaluation!.score < 4);
  const now = new Date();

  return (
    <div className="mx-auto max-w-4xl space-y-6">
      <div className="no-print flex justify-end"><PrintButton /></div>

      <header className="rounded-xl bg-navy-900 p-8 text-white">
        <div className="text-sm uppercase tracking-wider text-white/60">{profile.organization}</div>
        <h1 className="mt-1 text-3xl">Grant Opportunities Report</h1>
        <p className="mt-2 text-white/70">Generated {now.toLocaleString("en-US", { dateStyle: "long", timeStyle: "short" })}</p>
        <div className="mt-6 flex flex-wrap gap-4">
          <Tile value={evaluated.length} label="Evaluated (open)" />
          <Tile value={recommended.length} label="Recommended" accent />
          <Tile value={possible.length} label="Possible" />
        </div>
        {lastScan && (
          <table className="mt-6 w-full text-sm">
            <thead className="text-left text-xs uppercase tracking-wider text-white/50"><tr><th>Source</th><th className="text-right">Fetched in last scan</th></tr></thead>
            <tbody>{Object.entries(lastScan.bySource).map(([s, n]) => <tr key={s} className="border-t border-white/10"><td className="py-1">{s}</td><td className="text-right">{n}</td></tr>)}</tbody>
          </table>
        )}
      </header>

      <h2 className="border-b border-slate-300 pb-1 text-xl text-navy-900">Recommended opportunities</h2>
      {recommended.length === 0 && <p className="text-sm text-slate-500">None yet.</p>}
      {recommended.map((o) => <RecommendedCard key={o.id} o={o} />)}

      <h2 className="border-b border-slate-300 pb-1 text-xl text-navy-900">Possible fits</h2>
      {possible.map((o) => (
        <div key={o.id} className="print-break rounded-lg bg-white p-4 text-sm ring-1 ring-slate-200">
          <div className="flex justify-between gap-4">
            <Title o={o} />
            <span className="h-fit rounded bg-amber-600 px-2 py-1 font-semibold text-white">{o.evaluation!.score}/10</span>
          </div>
          <div className="text-xs text-slate-500">{o.agency} · <DeadlineChip iso={o.closeDate} /></div>
          <p className="mt-2 leading-relaxed">{o.evaluation!.whyItFits}</p>
        </div>
      ))}

      <h2 className="border-b border-slate-300 pb-1 text-xl text-navy-900">Not recommended</h2>
      <div className="divide-y divide-slate-200 rounded-lg bg-white text-sm ring-1 ring-slate-200">
        {notRecommended.map((o) => (
          <div key={o.id} className="flex justify-between gap-4 p-3">
            <div><span className="text-slate-500">{o.agency} · </span><Title o={o} inline /> — {o.evaluation!.whyItFits}</div>
            <span className="text-red-700">{o.evaluation!.score}/10</span>
          </div>
        ))}
      </div>

      <footer className="text-center text-xs text-slate-400">
        Forge Grants · Evaluations generated by Claude (Anthropic) and should be verified against each official notice.
      </footer>
    </div>
  );
}

function Tile({ value, label, accent }: { value: number; label: string; accent?: boolean }) {
  return (
    <div className="rounded-lg bg-white/10 px-6 py-3 text-center">
      <div className={`text-3xl ${accent ? "text-emerald-300" : ""}`}>{value}</div>
      <div className="text-xs text-white/70">{label}</div>
    </div>
  );
}

function Title({ o, inline }: { o: Opportunity; inline?: boolean }) {
  const cls = inline ? "text-navy-700" : "text-lg text-navy-700";
  return o.sourceUrl ? <a href={o.sourceUrl} className={cls}>{o.title}</a> : <Link href={`/opportunities/${encodeURIComponent(o.id)}`} className={cls}>{o.title}</Link>;
}

function RecommendedCard({ o }: { o: Opportunity }) {
  const ev = o.evaluation!;
  return (
    <article className="print-break space-y-3 rounded-lg bg-white p-5 text-sm leading-relaxed ring-1 ring-slate-200">
      <div>
        <span className="rounded bg-forge px-1.5 py-0.5 text-[10px] uppercase text-white">{o.source}</span>
        <h3 className="mt-1"><Title o={o} /></h3>
        <div className="text-slate-500">{o.agency}{o.number ? ` · ${o.number}` : ""}</div>
      </div>
      <div className="flex flex-wrap items-center gap-6 rounded bg-slate-50 p-3">
        <span className={`rounded px-3 py-1.5 text-xl text-white ${ev.score >= 8 ? "bg-emerald-700" : "bg-sky-700"}`}>{ev.score}/10</span>
        <div><div className="text-xs uppercase text-slate-500">Deadline</div><DeadlineChip iso={o.closeDate} /></div>
        <div><div className="text-xs uppercase text-slate-500">Award</div>{formatRange(o.awardFloor, o.awardCeiling)}</div>
        <div><div className="text-xs uppercase text-slate-500">Internal review</div>{formatDate(o.internalReviewDate)}</div>
      </div>
      <Block title="Why it fits">{ev.whyItFits}</Block>
      <Block title="Proposed project">{ev.proposedProject}</Block>
      <div className="grid gap-4 md:grid-cols-3">
        <Block title="Target clients">{ev.targetClients}</Block>
        <Block title="Recommended partners"><ol className="list-decimal pl-4">{ev.recommendedPartners.map((p) => <li key={p}>{p}</li>)}</ol></Block>
        <Block title="Why Forge qualifies">{ev.whyForgeQualifies}</Block>
      </div>
      {ev.risks.length > 0 && <Block title="Risks"><ul className="list-disc pl-4">{ev.risks.map((r) => <li key={r}>{r}</li>)}</ul></Block>}
    </article>
  );
}

function Block({ title, children }: { title: string; children: React.ReactNode }) {
  return <div><h4 className="font-medium text-navy-900">{title}</h4><div className="text-slate-700">{children}</div></div>;
}
